function clean(s) {
  if (!s) return "";
  return s
    .replace(/<[^>]*>/g, "")
    .replace(/@[^\s]*/g, "")
    .replace(/\(link[^)]*\)/gi, "")
    .replace(/MYMEMORY WARNING[^.]*\./gi, "")
    .replace(/á[\s\S]*?(?=\s|$)/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function lookupKhmer(korean) {
  if (BY_KOREAN[korean]) return BY_KOREAN[korean];
  const base = korean.split("/")[0].trim();
  if (BY_KOREAN[base]) return BY_KOREAN[base];
  const noSpace = korean.replace(/\s+/g, "");
  if (BY_KOREAN[noSpace]) return BY_KOREAN[noSpace];
  return null;
}

