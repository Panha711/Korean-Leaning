const src = readFileSync("src/data/eps-topik-vocabulary.ts", "utf8");

const entryRe =
  /\{\s*id:\s*"([^"]+)",\s*num:\s*(\d+),\s*korean:\s*"((?:\\.|[^"\\])*)",\s*lesson:\s*(\d+)\s*\}/g;

const entries = [];
let m;
while ((m = entryRe.exec(src)) !== null) {
  const korean = m[3].replace(/\\"/g, '"');
  const english = EN[korean] ?? "";
  entries.push({
    id: m[1],
    num: Number(m[2]),
    korean,
    english,
    lesson: Number(m[4]),
  });
}

const missing = entries.filter((e) => !e.english);
if (missing.length) {
  console.warn("Missing translations:", missing.length);
  missing.slice(0, 20).forEach((e) => console.warn(" -", e.korean));
}

const lines = [
  `/** EPS-TOPIK vocabulary from PPS Korean school PDF (សួរពាក្យ) */`,
  `export interface EpsVocabWord {`,
  `  id: string;`,
  `  num: number;`,
  `  korean: string;`,
  `  english: string;`,
  `  lesson: number;`,
  `}`,
  ``,
  `export const EPS_LESSON_LABELS: Record<number, string> = {`,
  `  1: "Introduction & countries",`,
  `  2: "Objects & pronouns",`,
  `  3: "Places & daily verbs",`,
  `  4: "Time & food",`,
  `  5: "Schedule & seasons",`,
  `  6: "Weather & family",`,
  `  7: "Honorifics & personality",`,
  `  8: "Counters & shopping",`,
  `  9: "Housework & kitchen",`,
  `  10: "Transport & grammar review",`,
  `  11: "More transport",`,
  `  12: "Grammar patterns",`,
  `};`,
  ``,
  `export const epsTopikVocabulary: EpsVocabWord[] = [`,
];

for (const w of entries) {
  const k = w.korean.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  const e = w.english.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  lines.push(
    `  { id: "${w.id}", num: ${w.num}, korean: "${k}", english: "${e}", lesson: ${w.lesson} },`,
  );
}

lines.push(`];`, ``);
lines.push(`export function getEpsWordsByLesson(lesson: number): EpsVocabWord[] {`);
lines.push(`  return epsTopikVocabulary.filter((w) => w.lesson === lesson);`);
lines.push(`}`, ``);
lines.push(`export function searchEpsVocabulary(query: string): EpsVocabWord[] {`);
lines.push(`  const q = query.trim().toLowerCase();`);
lines.push(`  if (!q) return epsTopikVocabulary;`);
lines.push(
  `  return epsTopikVocabulary.filter((w) => w.korean.toLowerCase().includes(q) || w.english.toLowerCase().includes(q) || String(w.num).includes(q));`,
);
