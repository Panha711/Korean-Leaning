export function getEpsVocabularyByLesson(lesson: number) {
  return epsTopikVocabulary.filter((w) => w.lesson === lesson);
}

export function searchEpsVocabulary(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return epsTopikVocabulary;
  return epsTopikVocabulary.filter(
    (w) =>
      w.korean.toLowerCase().includes(q) ||
      w.english.toLowerCase().includes(q) ||
      w.khmer.toLowerCase().includes(q) ||
      w.khmer.toLowerCase().includes(q) ||
      w.khmer.toLowerCase().includes(q) ||
      String(w.num).includes(q),
  );
}
