export function haeyoFormToDisplay(item: HaeyoFormItem) {
  return {
    id: item.id,
    num: item.num,
    korean: item.haeyoForm,
    english: `${item.meaning} (${item.dictionary})`,
    exampleKorean: `${item.stem} ${item.variation}`,
    exampleEnglish: item.category,
  };
}

export function searchHaeyoFormGrammar(query: string): HaeyoFormItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return haeyoFormGrammar;
  return haeyoFormGrammar.filter(
    (g) =>
      g.dictionary.toLowerCase().includes(q) ||
      g.meaning.toLowerCase().includes(q) ||
      g.haeyoForm.toLowerCase().includes(q) ||
      g.stem.toLowerCase().includes(q) ||
      g.variation.toLowerCase().includes(q) ||
      g.category.toLowerCase().includes(q) ||
      String(g.num).includes(q),
  );
}
